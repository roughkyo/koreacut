/** Translate diagnostics at display time so switching languages also updates errors. */
export function localizeMessage(message: string, language: Language = useLanguageStore.getState().language): string {
  if (language === "zh-CN") return message;
  if (Object.hasOwn(messages, message)) return messages[message];
  // Electron wraps rejected IPC errors. Preserve the operation and error prefix.
  const ipc = /^(Error invoking remote method '[^']+': (?:Error: )?)([\s\S]*)$/.exec(message);
  if (ipc) return ipc[1] + localizeMessage(ipc[2], language);
  if (message.startsWith("Error: ")) return "Error: " + localizeMessage(message.slice(7), language);
  for (const [pattern, translate] of patterns) {
    const match = pattern.exec(message);
    if (match) return translate(...match.slice(1));
  }
  return message;
}
